using IntelliQueryAI.AI.Common;
using IntelliQueryAI.AI.Telemetry;
using IntelliQueryAI.Domain.Entities.Forecasting;
using IntelliQueryAI.Domain.Services;
using Microsoft.Extensions.AI;
using Microsoft.Extensions.Logging;
using Microsoft.Extensions.Options;

namespace IntelliQueryAI.AI.Agents;

/// <summary>
/// Autonomous Microsoft Agent Framework agent specializing in statistical forecast interpretation,
/// methodology justification, goodness-of-fit appraisal, and downside risk articulation.
/// Core Invariant: Never fabricates numbers. All quantitative forecast values and confidence intervals
/// originate from the deterministic forecasting engine; this agent provides the qualitative, strategic,
/// and risk-adjusted narrative for decision makers.
/// </summary>
public sealed class ForecastAnalystAgent : BaseAgent
{
    private readonly ILogger<ForecastAnalystAgent> _logger;

    public ForecastAnalystAgent(
        IChatClient? chatClient,
        ITelemetryService telemetry,
        ILogger<ForecastAnalystAgent> logger,
        IOptions<AzureOpenAISettings> options,
        SimulationMode simulationMode)
        : base(
            chatClient,
            instructions: """
                You are the Principal Statistical Forecasting & Predictive Analytics Analyst Agent for IntelliQueryAI.
                Your role is to explain statistical forecasts generated by deterministic models (Ordinary Least Squares,
                Moving Averages, Double Exponential Smoothing, and Seasonal Compound Growth).

                CRITICAL INVARIANTS:
                - Never hallucinate or alter raw quantitative numbers. Use the exact values, growth rates, and confidence intervals provided by the engine.
                - Explain what the statistical method does in clear, authoritative, executive-friendly terms.
                - Characterize model fit (e.g., R-squared, Mean Absolute Error, volatility envelope width).
                - Detail the fundamental business assumptions underpinning the model.
                - Identify potential headwinds, structural breaks, or volatility risks that could breach the confidence interval.
                - Provide actionable planning recommendations (such as setting up What-If scenarios or monitoring thresholds).
                """,
            name: "ForecastAnalystAgent",
            description: "Interprets deterministic statistical forecast projections and articulates confidence envelopes.",
            tools: null,
            telemetry: telemetry,
            logger: logger,
            simulationMode: simulationMode,
            temperature: options?.Value?.Temperature ?? 0.2f)
    {
        _logger = logger;
    }

    public async Task<string> GenerateExplanationAsync(
        string metricName,
        string historicalPeriod,
        string forecastPeriod,
        ForecastMethod method,
        double confidenceLevel,
        IReadOnlyList<HistoricalDataPoint> historicalPoints,
        ForecastEngineOutput engineOutput,
        CancellationToken cancellationToken = default)
    {
        _logger.LogInformation(
            "Generating forecast explanation for metric '{MetricName}' using {Method} ({HistCount} historical points, {PredCount} predictions)",
            metricName, method, historicalPoints.Count, engineOutput.PredictionPoints.Count);

        try
        {
            var prompt = $"""
                Please review and explain the statistical forecast for metric: '{metricName}'.

                PARAMETERS:
                - Historical Window: {historicalPeriod} ({historicalPoints.Count} observations)
                - Forecast Window: {forecastPeriod} ({engineOutput.PredictionPoints.Count} projections)
                - Statistical Method: {method}
                - Confidence Interval: {confidenceLevel * 100:F0}% (Margin of error envelope)
                - Projected Overall Growth Rate: {engineOutput.ProjectedGrowthRate:+0.00;-0.00;0.00}%
                - Final Projected Value: {engineOutput.FinalProjectedValue:N2}
                - Model Goodness of Fit: R² = {engineOutput.RSquared:F3}, MAE = {engineOutput.MeanAbsoluteError:N2}

                RECENT HISTORICAL VALUES:
                {string.Join(", ", historicalPoints.TakeLast(6).Select(p => $"{p.Period}: {p.Value:N2}"))}

                PROJECTED TRAJECTORY (Mean [Lower, Upper]):
                {string.Join("\n", engineOutput.PredictionPoints.Select(p => $"- {p.Period}: {p.ForecastValue:N2} (95% CI: [{p.LowerBound:N2} .. {p.UpperBound:N2}])"))}

                KEY MODEL ASSUMPTIONS:
                {string.Join("\n", engineOutput.Assumptions.Select(a => $"- {a.Key} ({a.Value}): {a.Description}"))}

                Please provide an executive-ready statistical narrative formatted in Markdown with:
                1. Executive Summary & Trajectory Direction
                2. Statistical Methodology & Fit Assessment
                3. Key Assumptions & Boundary Conditions
                4. Downside/Upside Volatility Risks (Confidence Interval Analysis)
                5. Strategic Decision Recommendations
                """;

            var response = await ExecuteAsync(new AgentRequest(prompt), cancellationToken);
            return !string.IsNullOrWhiteSpace(response.Content)
                ? response.Content
                : GenerateSimulatedExplanation(metricName, historicalPeriod, forecastPeriod, method, confidenceLevel, historicalPoints, engineOutput);
        }
        catch (Exception ex)
        {
            _logger.LogWarning(ex, "Agent execution failed during forecast explanation; falling back to simulated explanation.");
            return GenerateSimulatedExplanation(metricName, historicalPeriod, forecastPeriod, method, confidenceLevel, historicalPoints, engineOutput);
        }
    }

    protected override string GenerateSimulatedResponse(AgentRequest request)
    {
        return """
            ### Executive Summary: Statistical Forecast Overview
            The statistical projection across the specified forecast horizon exhibits a stable expansion trajectory based on historical longitudinal momentum.

            ### Statistical Methodology & Goodness of Fit
            - **Modeling Technique**: Parametric trend extrapolation with rolling variance estimation.
            - **Confidence Envelope**: A 95% confidence interval is provided across each bucket, expanding over time to capture stochastic variance.

            ### Strategic Recommendations
            - **What-If Simulation**: Model sensitivity scenarios around critical cost or revenue drivers via the What-If Scenario Studio.
            - **Automated Threshold Monitoring**: Configure an alert monitor if actuals breach the forecast confidence envelope.
            """;
    }

    public static string GenerateSimulatedExplanation(
        string metricName,
        string historicalPeriod,
        string forecastPeriod,
        ForecastMethod method,
        double confidenceLevel,
        IReadOnlyList<HistoricalDataPoint> historicalPoints,
        ForecastEngineOutput engineOutput)
    {
        var firstHist = historicalPoints.FirstOrDefault()?.Value ?? 0;
        var lastHist = historicalPoints.LastOrDefault()?.Value ?? 0;
        var finalProj = engineOutput.FinalProjectedValue;
        var growth = engineOutput.ProjectedGrowthRate;

        string methodName = method switch
        {
            ForecastMethod.LinearTrend => "Ordinary Least Squares (OLS) Linear Trend Extrapolation",
            ForecastMethod.MovingAverage => "Trailing Simple Moving Average (SMA)",
            ForecastMethod.ExponentialSmoothing => "Double Exponential Smoothing (Holt-Winters)",
            ForecastMethod.SeasonalGrowth => "Compound Seasonal Growth & Multiplicative Drift",
            _ => "Statistical Trend Extrapolation"
        };

        string fitSummary = method switch
        {
            ForecastMethod.LinearTrend => $"Coefficient of Determination ($R^2 = {engineOutput.RSquared:F2}$) indicates that {(engineOutput.RSquared * 100):F1}% of variance is explained by the longitudinal trend.",
            ForecastMethod.ExponentialSmoothing => $"Smoothed level and trend parameters yielded a historical Mean Absolute Error (MAE) of {engineOutput.MeanAbsoluteError:N2}.",
            ForecastMethod.SeasonalGrowth => $"Geometric mean compounding reflects baseline momentum with an observed MAE of {engineOutput.MeanAbsoluteError:N2}.",
            _ => $"Baseline rolling smoothing demonstrates historical consistency with an MAE of {engineOutput.MeanAbsoluteError:N2}."
        };

        string direction = growth switch
        {
            > 5m => "robust upward trajectory",
            > 0m => "moderate positive expansion",
            < -5m => "notable contractionary trend",
            < 0m => "slight downward pressure",
            _ => "stable sideways consolidation"
        };

        return $"""
            ### Executive Summary: {metricName} Forecast
            The statistical projection for **{metricName}** across the horizon **{forecastPeriod}** exhibits a **{direction}**, tracking from the last observed baseline of **{lastHist:N2}** to an expected **{finalProj:N2}** (projected net delta of **{growth:+0.00;-0.00;0.00}%**).

            ### Statistical Methodology & Goodness of Fit
            - **Modeling Technique**: {methodName}.
            - **Model Diagnostics**: {fitSummary}
            - **Confidence Envelope**: A **{confidenceLevel * 100:F0}% confidence interval** has been computed across each future time bucket. Notice how the dispersion band widens across the horizon to represent cumulative stochastic variance.

            ### Key Model Assumptions
            {string.Join("\n", engineOutput.Assumptions.Select(a => $"- **{a.Key}** (`{a.Value}`): {a.Description}"))}

            ### Risk & Boundary Sensitivities
            1. **Tail-Risk Bounds**: While the base trajectory projects **{finalProj:N2}**, macroeconomic or supply chain shifts could drive outcomes toward the lower bound (**{engineOutput.PredictionPoints.LastOrDefault()?.LowerBound:N2}**) or upside acceleration (**{engineOutput.PredictionPoints.LastOrDefault()?.UpperBound:N2}**).
            2. **Structural Continuity**: The model assumes operational parameters established during **{historicalPeriod}** remain continuous without unmodeled regulatory or product deprecation shocks.

            ### Strategic Recommendations
            - **What-If Simulation**: Model sensitivity scenarios around critical cost or revenue drivers via the What-If Scenario Studio.
            - **Automated Threshold Monitoring**: Configure an alert monitor if actuals breach the $\pm{confidenceLevel * 100:F0}\%$ forecast envelope.
            """;
    }
}
